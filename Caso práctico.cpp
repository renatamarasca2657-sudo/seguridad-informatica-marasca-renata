# 1. Cinco riesgos de seguridad informática:
# 1. Robo de contraseñas de docentes y estudiantes.
# 2. Infección de las computadoras con virus.
# 3. Acceso de personas desconocidas a la red Wi-Fi.
# 4. Robo o filtración de información personal.
# 5. Pérdida de archivos y documentos importantes.

# 2. Una medida preventiva para cada riesgo:
# 1. Utilizar contraseñas seguras y diferentes.
# 2. Instalar y actualizar un antivirus.
# 3. Proteger el Wi-Fi con una contraseña segura.
# 4. Limitar el acceso a la información personal.
# 5. Realizar copias de seguridad periódicamente.

# 3. ¿Cómo protegerían la información personal de los estudiantes?
# Protegeríamos sus datos utilizando contraseñas seguras y permitiendo el acceso solamente a personas autorizadas. También evitaríamos compartir información personal y realizaríamos copias de seguridad para prevenir pérdidas.

# 4. Cinco reglas de seguridad informática:
# 1. No compartir contraseñas con otras personas.
# 2. No abrir enlaces ni archivos sospechosos.
# 3. Utilizar contraseñas seguras.
# 4. No compartir información personal en sitios desconocidos.
# 5. Cerrar las cuentas al terminar de utilizar las computadoras.